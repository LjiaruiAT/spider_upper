#pragma once

#include "leg_calc/common_types.hpp"

#include <Eigen/Dense>

namespace leg_calc {

// 按身体速度积分出 odom_T_base——给 RViz 一个"地面坐标系"。
//
// ---------------------------------------------------------------------------
// 为什么需要它
// ---------------------------------------------------------------------------
// URDF 的根 link 是 spider_base，**按定义它永远在世界原点**。RViz 又把
// Fixed Frame 设成它，于是机身被钉在原点，你只能看到六条腿在原地划水——
// 看不出机器人其实在往前走。
//
// 真实走路是"腿蹬地、机身平移"：缺的就是机身相对地面的那份运动。
// 补一个 odom 坐标系、发布 odom -> spider_base，RViz 把 Fixed Frame 改成 odom，
// 就能看到机器人横穿网格，而**支撑足在世界系里站住不动**——那才是"走路"
// 看起来应该有的样子。
//
// ---------------------------------------------------------------------------
// ⚠ 这是"按命令推算"，不是测出来的
// ---------------------------------------------------------------------------
// 积分的是**命令速度**，没有任何传感器参与。它等价于假设：
//   · 脚踩住了不打滑
//   · 舵机跟得上，步态真的走完了
//
// 真机上这两个假设都会破——打滑会让实际路程比显示的短，舵机跟不上会让
// 步态被下一个命令覆盖。所以 **不要**拿它当真实里程计用（不要接导航/建图）。
// 它的定位是**可视化辅助**：让"步态看起来对不对"这件事肉眼可见。
//
// 以后真机上有了回读或 IMU，把数据源换成真正的腿部里程计即可，
// 这个类的接口不用改。
class OdometryIntegrator {
public:
    // 用**已经乘过 motion_scale** 的身体速度推进 dt 秒。
    //
    // 为什么必须乘 motion_scale：足端位移被 motion_scale 缩放（见
    // foot_trajectory.hpp），起步/停步过渡期间脚并没有真把机身推动那么多。
    // 直接用命令速度积分，会让机身在该停的时候还在幽灵般地移动。
    //
    // twist 必须是**本体坐标系**下的速度（BodyTwist 的约定）。
    void update(const BodyTwist& scaled_twist, double dt);

    // 里程计坐标系 -> 身体坐标系。与 TF 约定一致：p_odom = odom_T_base * p_base。
    const Eigen::Isometry3d& odom_T_base() const { return odom_T_base_; }

    // 回到原点、朝向为零。节点重启时不需要手动调（对象本来就是新构造的），
    // 它主要给测试和"重新开始"的场合用。
    void reset();

private:
    Eigen::Isometry3d odom_T_base_{Eigen::Isometry3d::Identity()};
};

}  // namespace leg_calc
